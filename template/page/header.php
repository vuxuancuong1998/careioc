        ripple.style.cssText = `
            top: 50%;
            left: 50%;
            width: 0px;
            height: 0px;
            transform: translate(-50%, -50%);
            opacity: 1;
            transition: all 2.5s ease-out;
        `;
        
        button.appendChild(ripple);
        
        // Bắt đầu animation sau 10ms
        setTimeout(() => {
            ripple.style.width = '150px';
